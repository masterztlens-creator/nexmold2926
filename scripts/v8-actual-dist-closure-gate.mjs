/*
 * ============================================================================
 * CLOSURE ARTIFACT
 * ============================================================================
 */

function buildClosureArtifact(
  handoff,
  htmlManifest,
  matchedEntries,
  release,
  execution,
  consumption,
) {
  const manifest =
    matchedEntries
      .map(
        ({ entry }) =>
          Object.freeze({
            path:
              entry.path,
            route:
              entry.route,
            bytes:
              entry.bytes,
            sha256:
              entry.sha256,
          }),
      )
      .sort(
        (a, b) =>
          a.path.localeCompare(
            b.path,
          ),
      );

  return Object.freeze({
    schema:
      "nexmold.v8.actual-dist-production-closure.v1",

    buildEpoch:
      BUILD_EPOCH,

    handoff: Object.freeze({
      schema:
        handoff.schema,
      fingerprint:
        handoff.fingerprint,
    }),

    content: Object.freeze({
      id:
        handoff.contentId,
    }),

    decision: Object.freeze({
      id:
        handoff.decisionId,
    }),

    projection: Object.freeze({
      id:
        handoff.projectionId,
      fingerprint:
        handoff.projectionFingerprint,
    }),

    htmlManifest: Object.freeze({
      schema:
        htmlManifest.schema,
      epoch:
        htmlManifest.epoch,
      setSha256:
        htmlManifest.setSha256,
    }),

    release: Object.freeze({
      id:
        release.id,
      projectionId:
        release.projectionId,
      projectionFingerprint:
        release.projectionFingerprint,
      fingerprint:
        release.fingerprint,
      manifest,
    }),

    productionExecution:
      Object.freeze({
        schema:
          execution.schema,
        status:
          execution.status,
        executionId:
          execution.executionId,
        executionFingerprint:
          execution.executionFingerprint,
        releaseId:
          execution.releaseId,
        projectionId:
          execution.projectionId,
        releaseFingerprint:
          execution.releaseFingerprint,
        projectionFingerprint:
          execution.projectionFingerprint,
        manifest:
          [...execution.manifest],
      }),

    productionConsumption:
      Object.freeze({
        schema:
          consumption.schema,
        consumptionId:
          consumption.consumptionId,
        consumptionFingerprint:
          consumption.consumptionFingerprint,
        executionId:
          consumption.executionId,
        releaseId:
          consumption.releaseId,
        projectionId:
          consumption.projectionId,
        releaseFingerprint:
          consumption.releaseFingerprint,
        projectionFingerprint:
          consumption.projectionFingerprint,
        manifest:
          [...consumption.manifest],
      }),
  });
}

